#!/usr/bin/env node
// Stamps the build date into src/app/build-info.ts. Runs before `ng build`
// and `ng serve` (see package.json), so the footer's "Last updated" reflects
// the deploy that produced it. Dates are in Chicago time.
const fs = require('fs');
const path = require('path');

const date = new Intl.DateTimeFormat('en-US', {
  timeZone: 'America/Chicago', month: 'long', day: 'numeric', year: 'numeric',
}).format(new Date());

const out = path.join(__dirname, '..', 'src', 'app', 'build-info.ts');
fs.writeFileSync(out, `// Generated by scripts/write-build-info.js at build time. Do not edit.\nexport const BUILD_DATE = '${date}';\n`);
console.log(`build-info: ${date}`);
